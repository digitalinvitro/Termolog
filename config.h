// Разрядность конверсии DS18B20, бит. 9 бит = «родной» шаг 0.5 °C:
// точно соответствует формату хранения температуры (int8_t, °C×2,
// см. секцию «Температура» ниже) и сокращает конверсию с ~750 мс
// (12 бит) до ≤ 93.75 мс — меньше время бодрствования, меньше расход
// батареи.
constexpr uint8_t DS18B20_RESOLUTION      = 9;
