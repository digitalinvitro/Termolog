//  Диагностический флаг: сырые коды "raw/cal" последнего замера
//  VREFINT всегда пишутся в g_vddRaw/g_vddCal (см. power.cpp) —
//  их можно смотреть отладчиком или добавить вывод на экран
//  (в #if не используется; история диагностики — CHANGELOG.md).
constexpr bool VDD_DEBUG = false;

// ============================================================
//  Логирование с учётом режима сна.
//  При USE_STOP_MODE = true и LOG_VIA_USART1 = true весь лог
//  идёт через аппаратный USART1 (Serial1) вместо USB-CDC.
//  USART1 восстанавливается после STOP простой подачей тактирования,
//  в отличие от USB-CDC, который зависает на flush().
//
//  Подключение USB-TTL конвертера:
//    PA9  (TX)  -> RX конвертера
//    PA10 (RX)  -> TX конвертера
//    GND        -> GND
//    3V3        -> VCC (если конвертер без отдельного питания)
// ============================================================
// Приоритет веток: NO_LOG (полное отключение лога) → USART1 → USB-CDC.
//
// Объекты NoLogInstance и Serial1 — это ОПРЕДЕЛЕНИЯ, поэтому создаются
// в GLM.ino (ровно один раз на всю программу); здесь оставлены только
// extern-объявления и макросы.
#if defined(NO_LOG)
  // Тестовый режим без логирования — все LOG_OBJECT.* превращаются в no-op.
  class NoLogClass {
  public:
    template<typename T> void print(T) {}
    template<typename T> void println(T) {}
    template<typename T, typename U> void print(T, U) {}
    template<typename T, typename U> void println(T, U) {}
    void flush() {}
    int availableForWrite() { return 64; }
  };
  extern NoLogClass NoLogInstance;          // определение — в GLM.ino
  #define LOG_OBJECT  NoLogInstance
  #define LOG_BEGIN(baud)  ((void)0)
#elif USE_STOP_MODE && LOG_VIA_USART1
  // Ядро STM32duino ОБЪЯВЛЯЕТ 'extern Uart Serial1;' для любого чипа
  // с USART1, но СОЗДАЁТ объект только при HAVE_HWSERIAL1: для нашей
  // платы (variant.h, SERIAL_UART_INSTANCE=2) создаётся только Serial2 —
  // компиляция проходит, а линковка падает. Решение: создаём объект
  // сами — ровно той же строкой, что и ядро (см. GLM.ino; подробности
  // и альтернатива — в CHANGELOG.md). Конструктор не трогает железо
  // (таблицы PinMap), пины задаются в LOG_BEGIN ниже; ~192 байта RAM
  // (2 x 64 Б буферы + дескриптор).
  extern Uart Serial1;                      // определение — в GLM.ino
  #define LOG_OBJECT  Serial1
  #define LOG_BEGIN(baud)  do { \
      Serial1.setTx(PA9); \
      Serial1.setRx(PA10); \
      Serial1.begin(baud); \
    } while(0)
#else
  #define LOG_OBJECT  Serial
  #define LOG_BEGIN(baud)  Serial.begin(baud)
#endif

// Безопасный flush с таймаутом. Serial.flush() для USB-CDC блокирует
// бесконечно, если USB-периферия нерабочая. safeSerialFlush ждёт
// не более timeout_ms, потом возвращает управление.
// Опрашивается LOG_OBJECT (USART1 / USB / NoLog), а не «сырой»
// Serial — в режиме USART1 дожидаемся опустошения именно аппаратного
// TX-буфера (64 байта при 115200 бод уходят за ~6 мс, так что задержка
// фактически исчезающе мала).
// static inline: определён прямо в заголовке — доступен всем модулям
// (power.cpp, termo.cpp, GLM.ino) без порождения лишних символов.
static inline void safeSerialFlush(uint32_t timeout_ms = 50) {
  uint32_t t0 = millis();
  while (millis() - t0 < timeout_ms) {
    if (LOG_OBJECT.availableForWrite() == (int)SERIAL_TX_BUFFER_SIZE) break;
    delay(1);
  }
}

// Жив ли порт логирования для печати. Ветвление зеркалит выбор
// LOG_OBJECT выше:
//   NO_LOG           — все печати no-op по определению: для потока
//                      дампа «жив» всегда (ничего не отправляется,
//                      но и не блокируется);
//   USART1           — аппаратному UART хост не нужен: alive всегда;
//   USB-CDC          — жив только при сконфигурированном хосте;
//                      после Serial.end() или пропаже кабеля — false.
//                      Вызывается journalDumpCsv() каждые
//                      JOURNAL_DUMP_ALIVE_EVERY строк, чтобы
//                      пропажа хоста посреди дампа прерывала его,
//                      а не блокировала печать навечно.
// static inline — как safeSerialFlush: доступен всем модулям.
static inline bool logPortAlive() {
#if defined(NO_LOG)
  return true;
#elif USE_STOP_MODE && LOG_VIA_USART1
  return true;
#else
  return (bool)Serial;
#endif
}

