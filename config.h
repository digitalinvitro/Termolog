// ============================================================
//  Кнопка пробуждения -> линия EXTI и номер IRQ.
//  ВЫЧИСЛЯЮТСЯ ИЗ PIN_BUTTON: при смене пина кнопки достаточно
//  поменять одну строку выше — линия и IRQ обновятся сами
//  (используются в GLM.ino — глушение следов дребезга кнопки —
//  и в power.cpp prepareStopMode()).
//
//  Как это работает: каждый вывод PxN подключён к линии EXTIn —
//  номер вывода внутри порта равен номеру линии. Ядро STM32duino
//  кодирует PinName как (порт << 4) | номер вывода, поэтому
//  номер линии — младший нибл кода пина: PA15 -> 0x0F -> 15,
//  PB5 -> 0x15 -> 5. IRQ зависит от диапазона линии: 0..4 —
//  отдельные векторы EXTI0..EXTI4_IRQn, 5..9 — общий
//  EXTI9_5_IRQn, 10..15 — общий EXTI15_10_IRQn.
//
//  Требования при смене PIN_BUTTON: новый пин — именованный
//  вывод PxN (как и все пины этого конфига), и его нужно
//  исключить из списков парковки disableUnusedPinsAndPeripherals()
//  в power.cpp (иначе он уедет в Analog вместе с неиспользуемыми).
// ============================================================
constexpr uint32_t BUTTON_EXTI_LINE =
    static_cast<uint32_t>(PIN_BUTTON) & 0xFu;    // PA15 -> линия 15

constexpr IRQn_Type buttonExtiIrqn(uint32_t line) {
  if (line >= 10u) return EXTI15_10_IRQn;         // линии 10..15
  if (line >= 5u)  return EXTI9_5_IRQn;           // линии 5..9
  return static_cast<IRQn_Type>(EXTI0_IRQn + line); // линии 0..4 — свои векторы
}
constexpr IRQn_Type BUTTON_EXTI_IRQN = buttonExtiIrqn(BUTTON_EXTI_LINE);

