/* ============================================================
 *  termo.cpp — накопление и обработка температуры DS18B20
 * ============================================================
 *
 *  Содержит:
 *    - объекты датчика (oneWire, DallasTemperature);
 *    - TemperaturePipeline — конвейер обработки сырого отсчёта:
 *      ворот скорости + медианный фильтр из 3, состояние и логика
 *      обеих ступеней в одной структуре (единственный экземпляр —
 *      pipeline);
 *    - текущее и накопленные значения температуры
 *      (currentTempC / minTempC / maxTempC / hasData)
 *      в формате int8_t °C×2 (шаг 0.5 °C, рабочий диапазон
 *      -50..+50 °C — см. config.h, секция «Температура»);
 *    - состояние конвейера для ЭКРАНА: tempRawC (последний сырой
 *      отсчёт — крупная строка экрана ВСЕГДА) и tempRejected
 *      (флаг REJ) — пока ворот отбрасывает отсчёты, drawScreen()
 *      заменяет единицу "C" бейджем REJ и добавляет строку «hold»
 *      с замороженным достоверным значением;
 *    - initThermo()       — настройка датчика + первичное измерение:
 *                            первое чтение становится начальной
 *                            «ранее рассчитанной медианой» И эталоном
 *                            ворота (pipeline.seed());
 *    - fetchTempHalf()    — чтение готового результата конверсии,
 *                            округление к 0.5 °C и проверка диапазона;
 *    - fetchTempBlocking() — запрос + ожидание + чтение «сырого»
 *                            отсчёта (без фильтров);
 *    - readTemperature()  — запрос датчика: сырой отсчёт проходит
 *                            конвейер, возвращается выходное значение
 *                            (при отбрасывании — замороженное);
 *    - updateStats()      — обновление min/max С ПОДТВЕРЖДЕНИЕМ:
 *                            новый экстремум фиксируется после
 *                            EXTREMA_CONFIRM_SAMPLES замеров подряд
 *                            за его пределами;
 *    - resetStats()       — сброс диапазона min/max к текущей
 *                            температуре (кнопка PC11);
 *    - readAndLogSleepTemp() — чтение результата конверсии,
 *                            начатой перед конверсионным сном,
 *                            полный конвейер и лог «wake: TIMER».
 *
 *  Конвейер обработки (единый для всех потребителей):
 *    сырой отсчёт → проверка диапазона -50..+50 → ворот скорости
 *    → медиана из 3 → выход (currentTempC, min/max, экран, лог,
 *    журнал)
 *
 *  Лог сырых данных: при включённом терминале process() печатает
 *  каждый отсчёт строкой «[Thermo] raw T=... gate=OK/REJ»
 *  (перезахват — отдельным событием «[Thermo] RELOCK ...»);
 *  при NO_LOG все вызовы — no-op (батарейный режим не платит).
 *
 *  Общая конфигурация — в config.h.
 * ============================================================ */

