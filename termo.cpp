OneWire           oneWire(PIN_DS18B20);
DallasTemperature sensors(&oneWire);

// ============================================================
//  Температурные данные
// ============================================================
// ФОРМАТ ХРАНЕНИЯ: int8_t, значение = °C × 2 (шаг 0.5 °C).
// Примеры: +23 → +11.5 °C, -47 → -23.5 °C. Диапазон -100..+100.
int8_t currentTempC = 0;     // последнее успешное измерение, °C×2
int8_t minTempC     = 0;     // накопленный минимум с момента старта, °C×2
int8_t maxTempC     = 0;     // накопленный максимум с момента старта, °C×2
bool   hasData      = false; // true после первого успешного замера

// Состояние конвейера для ЭКРАНА. Крупная строка экрана ВСЕГДА
// показывает живой сырой отсчёт (tempRawC): табло интерактивно
// реагирует на любые изменения среды, и пользователь видит, что
// термометр работает. Пока ворот отбрасывает отсчёты, выход
// (currentTempC) заморожен, и drawScreen() информирует об этом:
// инвертированный бейдж REJ вместо единицы "C" + внизу строка
// «hold X.X C» с замороженным достоверным значением.
bool   tempRejected = false; // последний отсчёт отброшен воротом (флаг REJ)
int8_t tempRawC     = 0;     // последний сырой отсчёт, °C×2 (крупная строка экрана)

// Медиана трёх значений (сортирующая сеть из 3 сравнений)
static int8_t median3(int8_t a, int8_t b, int8_t c) {
  if (a > b) { int8_t t = a; a = b; b = t; }  // теперь a <= b
  if (b > c) { int8_t t = b; b = c; c = t; }  // теперь b <= c
  if (a > b) { int8_t t = a; a = b; b = t; }  // теперь a <= b <= c
  return b;
}

// Текущее время по RTC, секунды (wall-clock, работает и в STOP-циклах)
static uint32_t nowEpoch() {
  return STM32RTC::getInstance().getEpoch();
}

// ============================================================
//  TemperaturePipeline — конвейер обработки температуры:
//  ворот скорости + медиана из 3. Общая логика и ВСЁ состояние
//  двух ступеней собраны в этой структуре; единственный
//  экземпляр — pipeline (ниже).
//
//  Ступень 1 — ВОРТ СКОРОСТИ (gate): защита от быстрых сдвигов
//  показаний (солнечный луч на датчике и т.п.). Правила:
//    - эталон = последний ПРИНЯТЫЙ сырой отсчёт;
//    - |новый − эталон| <= TEMP_SLEW_MAX_RAW → ACCEPT, эталон
//      сдвигается;
//    - больше порога → REJECT: эталон остаётся на месте, выход
//      замораживается на последнем достоверном;
//    - перезахват: отброшенные отсчёты, стабильно держащие новый
//      уровень (в пределах того же порога) дольше TEMP_RELOCK_S
//      по RTC, признаются реальным изменением — RELOCK: эталон
//      и выход переключаются на него.
//  Физика порога и предел защиты — config.h (TEMP_SLEW_MAX_C,
//  TEMP_RELOCK_S). Время перезахвата меряется RTC (wall-clock),
//  а не счётчиком отсчётов — иначе в ACTIVE (замер раз в 5 с)
//  «10 минут» сжимались бы в ~3 минуты и защита зависела бы от
//  того, смотрит ли кто-то на экран.
//
//  Ступень 2 — МЕДИАНА ИЗ 3 (median): каждый отсчёт, ПРИНЯТЫЙ
//  воротом, пишется в окно по позиции счётчика; на каждом третьем
//  рассчитывается новая медиана (median3 — сортирующая сеть).
//  Запрос ВСЕГДА возвращает «ранее рассчитанную медиану», в том
//  числе пока окно ещё не заполнено. Отброшенные воротом и
//  невалидные чтения окно не сдвигают: оно собирает только
//  принятые отсчёты. Эффект: одиночный глитч внутри тройки
//  отбрасывается медианой; выход обновляется не чаще одного раза
//  на 3 принятых отсчёта (в SLEEP при периоде 15 с — раз в 45 с).
//
//  Полный путь — process(): вердикт ворота → строка сырого
//  отсчёта в терминал → выходное значение:
//    ACCEPT — отсчёт в окно, выход = «ранее рассчитанная медиана»;
//    RELOCK — выход прыгает на признанный уровень, окно
//             собирается заново (старые отсчёты неактуальны);
//    REJECT — выход заморожен («ранее рассчитанная медиана»).
//
//  Жизненный цикл: reset() — исходное состояние (до посева);
//  seed(raw) — первое чтение становится и медианой, и эталоном.
// ============================================================
struct TemperaturePipeline {
  // --- состояние ворота скорости ---
  bool     gateSeeded   = false; // true — эталон установлен (первым принятым отсчётом)
  int8_t   gateRef      = 0;     // эталон — последний принятый сырой отсчёт, °C×2
  uint32_t rejCount     = 0;     // длина текущей серии отбрасываний (для лога n=)
  int8_t   plateauCand  = 0;     // уровень плато-кандидата, °C×2
  uint32_t plateauSince = 0;     // RTC-момент установления уровня плато-кандидата

  // --- состояние медианного фильтра ---
  int8_t   window[3]  = {0, 0, 0}; // окно из 3 последних принятых отсчётов, °C×2
  uint8_t  count      = 0;         // счётчик отсчётов в окне (0..2, 3 = расчёт)
  int8_t   lastMedian = 0;         // «ранее рассчитанная медиана», °C×2

  // Вердикт ворота: ACCEPT — отсчёт принят; REJECT — отброшен
  // (выход заморожен); RELOCK — перезахват, уровень признан
  // реальным изменением.
  enum Verdict : uint8_t { ACCEPT, REJECT, RELOCK };

  void    reset();                    // исходное состояние (до первого seed)
  void    seed(int8_t raw);           // первое чтение: медиана И эталон
  Verdict gate(int8_t raw);           // ступень 1: вердикт ворота
  int8_t  median(int8_t sample);      // ступень 2: питание окна -> «ранее рассчитанная медиана»
  void    logRawSample(int8_t raw, Verdict v) const; // строка сырого отсчёта в терминал
  int8_t  process(int8_t raw, Verdict &outVerdict);  // полный путь: gate -> лог -> выход
};

// Единственный экземпляр конвейера (используют readTemperature()
// и readAndLogSleepTemp()).
TemperaturePipeline pipeline;

// ============================================================
//  TemperaturePipeline: реализации.
// ============================================================

// Исходное состояние: конвейер «пуст» — эталон не установлен
// (его посеет первый успешный отсчёт), медиана = заглушка 0.
void TemperaturePipeline::reset() {
  gateSeeded   = false;
  gateRef      = 0;
  rejCount     = 0;
  plateauCand  = 0;
  plateauSince = 0;
  count        = 0;
  lastMedian   = 0;
  window[0] = window[1] = window[2] = 0;
}

// Первое чтение (initThermo): становится начальной «ранее
// рассчитанной медианой» И эталоном ворота; окно собирается заново.
void TemperaturePipeline::seed(int8_t raw) {
  gateRef    = raw;
  gateSeeded = true;
  lastMedian = raw;
  count      = 0;
}

// Ступень 2: питает фильтр принятым отсчётом; возвращает
// «ранее рассчитанную медиану» (после возможного пересчёта).
int8_t TemperaturePipeline::median(int8_t sample) {
  window[count] = sample;         // запись по позиции счётчика
  count++;                        // инкремент счётчика отсчётов
  if (count >= 3) {               // счётчик равен трём:
    count = 0;                    // сброс счётчика,
    lastMedian = median3(window[0], window[1], window[2]);
  }                               // медиана — «ранее рассчитанная»
  return lastMedian;              // всегда возвращаем её
}

// Ступень 1: применяет ворот к сырому отсчёту. Эталон обновляется
// только принятым отсчётом или перезахватом.
TemperaturePipeline::Verdict TemperaturePipeline::gate(int8_t raw) {
  if (!gateSeeded) {              // самый первый отсчёт — становится эталоном
    gateRef    = raw;
    gateSeeded = true;
    return ACCEPT;
  }

  int16_t d = (int16_t)raw - (int16_t)gateRef;
  if (d >= -(int16_t)TEMP_SLEW_MAX_RAW && d <= (int16_t)TEMP_SLEW_MAX_RAW) {
    gateRef  = raw;               // принят — эталон сдвигается
    rejCount = 0;                 // серия отбрасываний прервана
    return ACCEPT;
  }

  // --- Отсчёт отброшен: отслеживаем серию и стабильность уровня ---
  if (rejCount == 0) {            // серия началась
    plateauCand  = raw;
    plateauSince = nowEpoch();
  } else {
    int16_t dp = (int16_t)raw - (int16_t)plateauCand;
    if (dp < -(int16_t)TEMP_SLEW_MAX_RAW || dp > (int16_t)TEMP_SLEW_MAX_RAW) {
      plateauCand  = raw;         // уровень ушёл (фаза роста) — плато считается заново
      plateauSince = nowEpoch();
    }
  }
  rejCount++;

  // --- Перезахват: плато держится дольше TEMP_RELOCK_S (по RTC) ---
  if (nowEpoch() - plateauSince >= TEMP_RELOCK_S) {
    int8_t oldRef = gateRef;
    gateRef  = raw;               // новый эталон
    rejCount = 0;                 // серия закрыта
    LOG_OBJECT.print(F("[Thermo] RELOCK ref="));
    LOG_OBJECT.print(oldRef * 0.5f, 1);
    LOG_OBJECT.print(F(" -> "));
    LOG_OBJECT.print(raw * 0.5f, 1);
    LOG_OBJECT.println(F(" (stable level admitted)"));
    return RELOCK;
  }
  return REJECT;
}

// Строка сырого отсчёта в терминал (если терминал включен).
// При NO_LOG все вызовы — no-op: батарейный режим за отладку
// не платит ни временем, ни током.
void TemperaturePipeline::logRawSample(int8_t raw, Verdict v) const {
  LOG_OBJECT.print(F("[Thermo] raw T="));
  LOG_OBJECT.print(raw * 0.5f, 1);
  if (v == ACCEPT) {
    LOG_OBJECT.println(F(" gate=OK"));
  } else if (v == REJECT) {
    LOG_OBJECT.print(F(" gate=REJ ref="));
    LOG_OBJECT.print(gateRef * 0.5f, 1);
    LOG_OBJECT.print(F(" n="));
    LOG_OBJECT.println(rejCount); // n = сколько подряд отброшено
  }
  // RELOCK уже напечатан событием «[Thermo] RELOCK ...»
}

// Полный путь сырого отсчёта: вердикт ворота -> строка в терминал
// -> выходное значение конвейера (контракт — в шапке структуры).
int8_t TemperaturePipeline::process(int8_t raw, Verdict &outVerdict) {
  Verdict v = gate(raw);
  logRawSample(raw, v);
  outVerdict = v;

  if (v == ACCEPT) {
    return median(raw);
  }
  if (v == RELOCK) {
    lastMedian = raw;             // выход прыгает на признанный уровень
    count = 0;                    // окно собирается заново
    return raw;
  }
  return lastMedian;              // REJECT: выход заморожен
}

// ============================================================
//  Вспомогательное: чтение ГОТОВОГО результата конверсии
//  (без запроса и без ожидания). При успехе записывает в out
//  значение в формате °C×2 и возвращает true; false — датчик
//  не отвечает или замер вне рабочего диапазона -50..+50 °C.
// ============================================================
static bool fetchTempHalf(int8_t &out) {
  float t = sensors.getTempCByIndex(0);
  if (t == DEVICE_DISCONNECTED_C) {
    return false;            // обрыв / КЗ / датчик не отвечает
  }
  // Приведение к формату хранения: ближайшее значение, кратное 0.5 °C.
  // При 9-битном разрешении датчик сам выдаёт кратные 0.5 °C значения;
  // округление — страховка на случай иной разрядности.
  int16_t half = (int16_t)lroundf(t * 2.0f);
  if (half < TEMP_RANGE_MIN_RAW || half > TEMP_RANGE_MAX_RAW) {
    return false;            // вне рабочего диапазона -50..+50 °C
  }
  out = (int8_t)half;
  return true;
}

// ============================================================
//  Вспомогательное: запрос температуры «сырым» отсчётом
//  (блокирующий вариант: запрос + ожидание + чтение, без фильтров).
// ============================================================
static bool fetchTempBlocking(int8_t &out) {
  sensors.requestTemperatures();
  // Блокирующее ожидание преобразования. 9-бит ≈ 94 мс.
  // Это приемлемо: ~0.1 с из каждых 15 с (<1 %) в режиме сна.
  delay(DS18B20_CONV_MS);
  return fetchTempHalf(out);
}

// ============================================================
//  Стартовая инициализация датчика + первичное измерение
//  (посев конвейера). Вызывается один раз из setup(). Действия:
//    1) запуск DS18B20: 9 бит (шаг 0.5 °C), ожидание — на нашей
//       стороне (setWaitForConversion(false));
//    2) конвейер — в исходное состояние (pipeline.reset());
//    3) немедленное чтение значения из датчика: при успехе оно
//       становится начальной «ранее рассчитанной медианой» и
//       эталоном ворота (pipeline.seed());
//    4) первичное измерение инициализирует min/max.
//  При ошибке датчика: конвейер остаётся в исходном состоянии —
//  медиана = заглушка 0, эталон ворота не установлен (посеет
//  первый успешный отсчёт), min/max будут установлены первым же
//  принятым значением (hasData = false).
// ============================================================
void initThermo() {
  sensors.begin();
  sensors.setResolution(DS18B20_RESOLUTION);  // 9 бит: шаг 0.5 °C
  sensors.setWaitForConversion(false);        // сами ждём через delay()

  pipeline.reset();             // конвейер — в исходное состояние

  int8_t raw;
  if (fetchTempBlocking(raw)) {
    pipeline.seed(raw);         // первое чтение: медиана И эталон
    currentTempC = raw;
    tempRawC     = raw;         // сырое значение — и на экран
    tempRejected = false;       // отбрасываний ещё не было (нет REJ)
    updateStats(raw);           // первичное измерение инициализирует min/max
    LOG_OBJECT.print(F("[Thermo] seed T = "));
    LOG_OBJECT.print(raw * 0.5f, 1);
    LOG_OBJECT.println(F(" C"));
  } else {
    tempRejected = false;       // экран стартует без флага REJ
    LOG_OBJECT.println(F("[Thermo] DS18B20 not responding"));
  }
}

// ============================================================
//  Запрос значения у датчика: сырой отсчёт проходит конвейер
//  (ворот скорости + медианный фильтр).
//  true  — датчик ответил, в out — выход конвейера (при
//          отбрасывании воротом — замороженное последнее
//          достоверное значение);
//  false — ошибка чтения (состояние конвейера не трогается).
// ============================================================
bool readTemperature(int8_t &out) {
  int8_t raw;
  if (!fetchTempBlocking(raw)) {
    return false;               // ошибка: конвейер не трогаем
  }
  TemperaturePipeline::Verdict v;
  out = pipeline.process(raw, v);
  tempRawC     = raw;           // живой сырой отсчёт — на экран (REJ-режим, drawScreen)
  tempRejected = (v == TemperaturePipeline::REJECT);
  journalOnSample(nowEpoch(), out); // выход конвейера — в журнал
  return true;
}

// ============================================================
//  Обновление минимума/максимума С ПОДТВЕРЖДЕНИЕМ.
//  Новый экстремум фиксируется только после
//  EXTREMA_CONFIRM_SAMPLES замеров ПОДРЯД за пределами текущего
//  экстремума (в SLEEP 4 × 15 с = 1 мин): короткие (меньше
//  минуты) выходы за диапазон в статистику не попадают.
//  Пока подтверждение не набрано, копится кандидат — самое
//  глубокое значение серии; оно и фиксируется при подтверждении.
// ============================================================
static int8_t  pendMin  = 0;   // кандидат нового минимума, °C×2
static uint8_t pendMinN = 0;   // счётчик подтверждения минимума
static int8_t  pendMax  = 0;   // кандидат нового максимума, °C×2
static uint8_t pendMaxN = 0;   // счётчик подтверждения максимума

void updateStats(int8_t t) {   // t — температура в формате °C×2
  if (!hasData) {
    minTempC = maxTempC = t;
    hasData  = true;
    return;
  }

  if (t < minTempC) {                        // кандидат минимума
    if (pendMinN == 0 || t < pendMin) {
      pendMin = t;                           // кандидат углубляется
    }
    if (++pendMinN >= EXTREMA_CONFIRM_SAMPLES) {
      minTempC = pendMin;                    // подтверждён — фиксируем
      pendMinN = 0;
    }
  } else {
    pendMinN = 0;                            // серия прервана
  }

  if (t > maxTempC) {                        // кандидат максимума
    if (pendMaxN == 0 || t > pendMax) {
      pendMax = t;                           // кандидат растёт
    }
    if (++pendMaxN >= EXTREMA_CONFIRM_SAMPLES) {
      maxTempC = pendMax;                    // подтверждён — фиксируем
      pendMaxN = 0;
    }
  } else {
    pendMaxN = 0;                            // серия прервана
  }
}

// ============================================================
//  Сброс диапазона температур (кнопка PC11).
//  Сбрасывает и неподтверждённых кандидатов экстремумов.
// ============================================================
void resetStats() {
  minTempC = currentTempC;
  maxTempC = currentTempC;
  pendMinN = 0;
  pendMaxN = 0;
  LOG_OBJECT.println(F("[Thermo] stats RESET by user"));
}

// ============================================================
//  Замер и лог SLEEP-цикла. Вызывается ПОСЛЕ завершённой
//  конверсии DS18B20: конверсия высиживается двумя способами
//  (deepSleep в STOP-режиме или блокирующий delay — выбор в
//  waitForConversion(), GLM.ino), а полный конвейер после
//  пробуждения общий для обоих
//  путей: диапазон → ворот скорости → медиана → статистика.
//  Один и тот же ряд питает экран, min/max и лог.
// ============================================================
void readAndLogSleepTemp() {
  int8_t raw;
  if (fetchTempHalf(raw)) {
    TemperaturePipeline::Verdict v;
    int8_t t = pipeline.process(raw, v);
    tempRawC     = raw;        // живой сырой отсчёт — на экран (REJ-режим, drawScreen)
    tempRejected = (v == TemperaturePipeline::REJECT);
    currentTempC = t;
    updateStats(t);
    journalOnSample(nowEpoch(), t);   // выход конвейера — в журнал
    LOG_OBJECT.print(F("[Thermo] wake: TIMER  T="));
    LOG_OBJECT.print(currentTempC * 0.5f, 1);
    LOG_OBJECT.print(F("  range=["));
    LOG_OBJECT.print(minTempC * 0.5f, 1);
    LOG_OBJECT.print(F(" .. "));
    LOG_OBJECT.print(maxTempC * 0.5f, 1);
    LOG_OBJECT.println(F("]"));
    safeSerialFlush(100);
  } else {
    LOG_OBJECT.println(F("[Thermo] wake: TIMER  DS18B20 error"));
  }
}
